/*
 * =========================================================
 * abstract と interface
 * =========================================================
 *
 * ■ abstract
 * 「未完成のクラス・関数」を作るためのもの。
 *
 * ■ interface
 * 「この機能を持ってください」という契約。
 *
 * Swiftでいうと、
 *
 * interface ≒ protocol
 *
 * abstract class はSwiftには完全に同じものはない。
 */


/*
 * =========================================================
 * 1. interface
 * =========================================================
 *
 * interfaceは「この機能を持ってください」という契約。
 */

interface Animal {

    // Animalを実装するクラスは
    // cry()を必ず用意してください。
    fun cry()
}


/*
 * interfaceを実装する。
 */

class Dog : Animal {

    // Animalで決められているcry()を実装する。
    override fun cry() {
        println("ワンワン")
    }
}


/*
 * interfaceのポイント
 *
 * Animal
 *   ↓
 * 「cry()を持ってね」
 *
 * Dog
 *   ↓
 * 「わかった。cry()はこうする」
 */


/*
 * =========================================================
 * 2. abstract class
 * =========================================================
 *
 * abstract classは「未完成のクラス」。
 *
 * そのまま使うことはできない。
 */

abstract class AnimalBase {

    // 「cry()は子クラスで実装してね」
    abstract fun cry()

    // 普通の関数も持てる。
    // これはここで実装しておく。
    fun eat() {
        println("食べる")
    }
}


/*
 * AnimalBaseを継承する。
 */

class Cat : AnimalBase() {

    // abstract funなので、
    // Cat側で実装する必要がある。
    override fun cry() {
        println("ニャー")
    }
}


/*
 * Catは使える。
 */

fun main() {

    val cat = Cat()

    cat.cry()   // ニャー
    cat.eat()   // 食べる
}


/*
 * =========================================================
 * 3. interface と abstract class の違い
 * =========================================================
 *
 *
 * interface
 * ------------------------------
 *
 * 「この機能を持ってください」
 *
 *     interface Animal {
 *         fun cry()
 *     }
 *
 *
 * abstract class
 * ------------------------------
 *
 * 「共通の処理を持った未完成のクラス」
 *
 *     abstract class AnimalBase {
 *
 *         abstract fun cry()
 *
 *         fun eat() {
 *             println("食べる")
 *         }
 *     }
 *
 *
 * つまり、
 *
 * interface
 *     → 契約
 *     → 「何ができるか」
 *
 * abstract class
 *     → 未完成の親クラス
 *     → 「共通処理 + 子クラスに任せる処理」
 *
 *
 * =========================================================
 * 4. abstract funとは？
 * =========================================================
 *
 * abstract fun cry()
 *
 * は、
 *
 * 「cryという関数は必要だけど、
 *  ここでは中身を書かない。
 *  子クラスで書いてね」
 *
 * という意味。
 *
 *
 * =========================================================
 * 5. 超重要な覚え方
 * =========================================================
 *
 * interface
 *     ↓
 * 「こういう機能を持ってね」
 *
 * abstract class
 *     ↓
 * 「共通部分は用意するけど、
 *  一部は子クラスで完成させてね」
 *
 * abstract fun
 *     ↓
 * 「この関数は子クラスで実装してね」
 */